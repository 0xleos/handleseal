#!/usr/bin/env python3
"""Copy the Handleseal ABI into the static frontend. Never broadcasts."""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ARTIFACT = ROOT / "out" / "Handleseal.sol" / "Handleseal.json"
TARGET = ROOT / "frontend" / "js" / "abi.js"
REQUIRED = {
    "seal",
    "witness",
    "getSeal",
    "sealsOf",
    "sealsByHash",
    "witnessesOf",
    "isAgent",
    "agentHandle",
    "hasWitnessed",
    "sealCount",
    "REGISTRY",
    "MAX_LABEL_BYTES",
}


def load_abi():
    artifact = json.loads(ARTIFACT.read_text())
    abi = artifact["abi"]
    names = {item.get("name") for item in abi if item.get("name")}
    missing = REQUIRED - names
    if missing:
        raise SystemExit(f"ABI is missing {sorted(missing)}")
    return abi


def render(abi):
    body = json.dumps(abi, indent=2)
    return (
        "// Generated by script/sync_abi.py from contracts/Handleseal.sol.\n"
        "// Do not edit by hand. Regenerate with script/predict_create2.sh --write\n"
        f"window.HANDLESEAL_ABI = {body};\n"
    )


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    abi = load_abi()
    text = render(abi)
    if mode == "write":
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text)
        print(f"wrote {TARGET}")
        return
    if not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit("frontend/js/abi.js is stale. Run script/predict_create2.sh --write")
    print("abi ok")


if __name__ == "__main__":
    main()
